-- Canonical unified schema for `public.running_logs` on Supabase project `running-tracker` (`mwjurzrnkpnqsfqrhaex`).
-- Safe to run both on a fresh database and on the existing `running_logs` table.

create table if not exists public.running_logs (
    id bigint generated by default as identity primary key,
    hc_session_id text not null unique,
    run_date timestamptz not null,
    workout_type text not null default '야외',
    source_package text,
    title text,
    ended_at timestamptz,
    distance_km numeric not null default 0 check (distance_km >= 0),
    distance_meters numeric check (distance_meters is null or distance_meters >= 0),
    duration_sec integer not null default 0 check (duration_sec >= 0),
    avg_pace_sec integer,
    avg_hr integer,
    max_hr integer,
    min_hr integer,
    zone2_min_bpm integer,
    zone2_max_bpm integer,
    zone2_ratio numeric check (zone2_ratio is null or (zone2_ratio >= 0 and zone2_ratio <= 1)),
    zone2_pct numeric check (zone2_pct is null or (zone2_pct >= 0 and zone2_pct <= 100)),
    avg_cadence integer,
    -- 1-minute downsampled JSONB array:
    -- [{"minute":1,"offset_sec":0,"timestamp":"2026-11-24T06:00:00Z",
    --   "hr":135,"max_hr":140,"min_hr":130,"zone2_ratio":1.0,
    --   "pace_sec":300,"cadence":172,"distance_m":200.0}]
    timeseries_1min jsonb not null default '[]'::jsonb,
    notes text,
    synced_at timestamptz not null default now(),
    created_at timestamptz default now(),
    updated_at timestamptz not null default now()
);

-- Idempotent extension columns for existing `public.running_logs`
alter table public.running_logs add column if not exists source_package text;
alter table public.running_logs add column if not exists title text;
alter table public.running_logs add column if not exists ended_at timestamptz;
alter table public.running_logs add column if not exists distance_meters numeric;
alter table public.running_logs add column if not exists min_hr integer;
alter table public.running_logs add column if not exists zone2_min_bpm integer;
alter table public.running_logs add column if not exists zone2_max_bpm integer;
alter table public.running_logs add column if not exists zone2_pct numeric;
alter table public.running_logs add column if not exists notes text;
alter table public.running_logs add column if not exists synced_at timestamptz not null default now();
alter table public.running_logs add column if not exists updated_at timestamptz not null default now();

create index if not exists idx_running_logs_run_date
    on public.running_logs (run_date desc);

create index if not exists idx_running_logs_timeseries_gin
    on public.running_logs using gin (timeseries_1min jsonb_path_ops);

create or replace function public.set_running_logs_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
    new.updated_at = now();
    return new;
end;
$$;

drop trigger if exists trg_running_logs_updated_at on public.running_logs;
create trigger trg_running_logs_updated_at
    before update on public.running_logs
    for each row
    execute function public.set_running_logs_updated_at();

grant usage on schema public to anon, authenticated;
grant select, insert, update, delete on table public.running_logs to anon, authenticated;

alter table public.running_logs enable row level security;

drop policy if exists "Allow full access for personal tracker" on public.running_logs;
create policy "Allow full access for personal tracker"
    on public.running_logs
    for all
    to public
    using (true)
    with check (true);
